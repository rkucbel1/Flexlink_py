#!/usr/bin/env python3
"""
Get_Decoded_Bitstream.py - Decode the received encoded bitstream into transport blocks.
Reverse of Tx/Construct_Encoded_Bitstream_Tx.py.

Steps:
  1. Read Parameters_Rx_payload.json from the Rx directory.
  2. Load the bitstream from the file named in File_Rx/Bitstream_Encoded_Rx (written
     by Get_Demapped_Bitstream.py): hard bits 0/1 or soft values 0..1 (P(bit = 1)).
  3. Check its length == Calculated_Rx/ScrambledSequenceSize (= NumberOfDataSigs).
  4. Descramble the whole sequence with the Gold code for Defined_Rx/C_init_Dat,
     generated by scrambler_gc() from Scrambler/Scrambler_GC.py (not kept on disk).
     A soft value v is flipped to 1 - v where the Gold code bit is 1.
  5. Drop the trailing ZeroPadding values (their errors are reported as a check)
     and split the rest into AvailableDataBlocks code words of CodeWordSize.
  6. For each code word, undo the Tx stages in reverse order, using the functions
     of the Rx stage scripts in Rx/Decode/:
         Rate_Matching_Rx  -> average the Repetition + 1 copies   (= CodeBlockSize)
         Interleaver_Rx    -> DeInterleave_LDPC, same length
         FEC_LDPC_Rx       -> LDPC_Decode with H, K message bits  (= DataBlockSize)
         Check_CRC         -> recompute the CRC, PASS/FAIL, strip it (= TransportBlockSize)
     and append the transport block to the output bitstream.
  7. Save the bitstream to the file named in File_Rx/Bitstream_TransportBlks_Rx in
     the Rx directory (or --out), in the same layout as the Tx input file
     Bitstream_TransportBlks_Tx.h5.
  8. With --compare, compare it bit by bit with the Tx transport blocks.

Nothing is written to the JSON.

Exit status: 0 = every CRC passed (and --compare matched), 2 = a CRC failed or
--compare found differences, 1 = input/setup error, 3 = unexpected error.

Usage:
    python Get_Decoded_Bitstream.py
    python Get_Decoded_Bitstream.py --iterations 30
    python Get_Decoded_Bitstream.py --compare            # vs Tx/Generate_RandomPacketOfData/Bitstream_TransportBlks_Tx.h5
    python Get_Decoded_Bitstream.py --compare other.h5 --out My_Blocks.h5
    python Get_Decoded_Bitstream.py --ray 2 --compare  # antenna 2: *_Ray2.h5 in and out
    (default: *_Combined.h5 when the run has several antennas, else *_Ray1.h5)

The output .h5 file contains:
    TransportBlock_Bitstream  (AvailableDataBlocks * TransportBlockSize,) uint8
    CRC_Pass                  (AvailableDataBlocks,) uint8   1 = CRC passed for that block
    attrs  AvailableDataBlocks, TransportBlockSize, CRC_Gen, BlocksPassed,
           CorrectedBits, PaddingErrors, C_init_Dat, Iterations, SourceFile
"""

