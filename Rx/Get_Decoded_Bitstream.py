RX_DIR = Path(__file__).resolve().parent          # the Rx folder
PARAMS_FILENAME = "Parameters_Rx_payload.json"
DEFINED_SECTION = "Defined_Rx"
C_INIT_MAX = 255     # C_init_Dat comes from the 8-bit control field C_init
CALCULATED_SECTION = "Calculated_Rx"
FILE_SECTION = "File_Rx"

INPUT_KEY = "Bitstream_Encoded_Rx"              # File_Rx/<key> = input name (Rx directory)
OUTPUT_KEY = "Bitstream_TransportBlks_Rx"       # File_Rx/<key> = output name (Rx directory)
INPUT_DATASET = "data"
OUTPUT_DATASET = "TransportBlock_Bitstream"     # same dataset name as Bitstream_TransportBlks_Tx.h5
DECODE_DIR = RX_DIR / "Decode"     # Rate_Matching_Rx, Interleaver_Rx, FEC_LDPC_Rx, Check_CRC
SCRAMBLER_SCRIPT = "Scrambler_GC.py"
DEFAULT_ITERATIONS = 15
DEFAULT_COMPARE = TX / "Generate_RandomPacketOfData" / "Bitstream_TransportBlks_Tx.h5"
SHOW_ERRORS = 10

EXIT_OK, EXIT_ERROR, EXIT_FAIL, EXIT_UNEXPECTED = 0, 1, 2, 3

log = logging.getLogger("Get_Decoded_Bitstream")


# --------------------------------------------------------------------------- #
# Rx scripts, loaded by file path so their helper functions can be reused.
# The four stage scripts live in Rx/Decode/.
# --------------------------------------------------------------------------- #
def load_rx_module(name: str, folder: Path = DECODE_DIR) -> ModuleType:
    path = folder / f"{name}.py"
    if not path.is_file():
        raise FileNotFoundError(f"{path.name} not found in {folder}")
    spec = importlib.util.spec_from_file_location(f"_rx_{name}", path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class Decoder:
    """The four Rx stages, set up once from the JSON and applied per code word."""

    def __init__(self, params: dict[str, Any], iterations: int = DEFAULT_ITERATIONS):
        rm_mod = load_rx_module("Rate_Matching_Rx")
        il_mod = load_rx_module("Interleaver_Rx")
        ldpc_mod = load_rx_module("FEC_LDPC_Rx")
        crc_mod = load_rx_module("Check_CRC")

        # Rate matching
        self.repetition = rm_mod.get_repetition(params)
        self._deconstruct = rm_mod.load_deconstruct(rm_mod.rate_match_dirs(None))

        # Interleaver
        self.cbs = il_mod.get_block_size(params)
        self._deinterleave = il_mod.load_deinterleaver(il_mod.resolve_interleaver_dir(None))

        # LDPC
        self.n = ldpc_mod.get_block_size(params)
        if self.cbs != self.n:
            raise ValueError(f"Interleaver block size {self.cbs} != EncoderBlockSize {self.n}")
        rate_str, rate = ldpc_mod.get_code_rate(params)
        k_frac = self.n * rate
        if k_frac.denominator != 1:
            raise ValueError(f"EncoderBlockSize {self.n} x EncoderCodeRate {rate_str} "
                             "is not a whole number of bits")
        self.k = int(k_frac)
        get_h, self._ldpc_decode = ldpc_mod.load_decoder(ldpc_mod.resolve_ldpc_dir(None))
        self.h_type = ldpc_mod.h_type(self.n, rate_str)
        self.H = np.asarray(get_h(self.h_type))
        if self.H.shape != (self.n - self.k, self.n):
            raise ValueError(f"LDPC_Get_H('{self.h_type}') returned H of shape {self.H.shape}, "
                             f"expected ({self.n - self.k}, {self.n})")
        self.iterations = iterations

        # CRC
        self.crc_gen = crc_mod.crc_gen_name(params, None)
        self._generate_crc = crc_mod.load_generate_crc(crc_mod.resolve_crc_dir(None))
        self.crc_len = np.asarray(self._generate_crc(np.zeros(1, dtype=np.uint8), self.crc_gen)).size
        self.bit_string = crc_mod.bit_string

        log.info("Repetition %d | deinterleaver %d | LDPC %s (K=%d, N=%d, %d iterations) | CRC %s",
                 self.repetition, self.cbs, self.h_type, self.k, self.n, iterations, self.crc_gen)

    def __call__(self, word: np.ndarray) -> tuple[np.ndarray, bool, int]:
        """One code word (soft 0..1) -> (transport block bits, CRC passed, bits corrected)."""
        # 1. Rate_Matching_Rx: average the Repetition + 1 copies
        inv = np.asarray(self._deconstruct(word, self.repetition), dtype=np.float64).ravel()
        if inv.size % self.cbs:
            raise ValueError(f"Rate de-matched block of {inv.size} values is not a multiple of "
                             f"the code block size {self.cbs}")
        m = inv.size // self.cbs

        # 2. Interleaver_Rx
        code = np.asarray(self._deinterleave(inv.reshape(m, self.cbs), self.cbs), dtype=np.float64)

        # 3. FEC_LDPC_Rx: values 0..1 -> beliefs (negative = bit 0, positive = bit 1)
        beliefs = 2.0 * code - 1.0
        data_blk = np.asarray(self._ldpc_decode(beliefs, self.H, NumberOfIterations=self.iterations),
                              dtype=np.uint8).reshape(m, self.k)
        corrected = int(((beliefs[:, :self.k] > 0).astype(np.uint8) != data_blk).sum())
        data_blk = data_blk.ravel()

        # 4. Check_CRC
        if data_blk.size <= self.crc_len:
            raise ValueError(f"Data block of {data_blk.size} bits is not longer than the CRC")
        tb, received_crc = data_blk[:-self.crc_len], data_blk[-self.crc_len:]
        calculated_crc = np.asarray(self._generate_crc(tb, self.crc_gen)).ravel().astype(np.uint8)
        return tb, bool(np.array_equal(calculated_crc, received_crc)), corrected


# --------------------------------------------------------------------------- #
# Descrambler (the Gold code from Scrambler_GC.py)
# --------------------------------------------------------------------------- #
def gold_code(c_init: int, length: int) -> np.ndarray:
    """The scrambling Gold code: scrambler_gc() applied to all zeros."""
    script = SCRAMBLER / SCRAMBLER_SCRIPT
    if not script.is_file():
        raise FileNotFoundError(f"{SCRAMBLER_SCRIPT} not found in {SCRAMBLER}")
    # Scrambler_GC imports Scrambler_Gold_Code_Generator from its own folder
    if str(SCRAMBLER) not in sys.path:
        sys.path.insert(0, str(SCRAMBLER))
    spec = importlib.util.spec_from_file_location("Scrambler_GC", script)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    scrambler_gc = getattr(module, "scrambler_gc", None)
    if not callable(scrambler_gc):
        raise ValueError(f"{script} has no scrambler_gc function")
    # scrambler_gc always writes its Gold code to an .h5 file; give it a
    # temporary one that is deleted straight away, so nothing is kept in Rx/.
    with tempfile.TemporaryDirectory() as tmp:
        code = np.asarray(scrambler_gc(c_init, np.zeros(length, dtype=np.uint8),
                                       h5_file=str(Path(tmp) / "GC_Scrambler_Sequence.h5")))
    code = code.ravel().astype(np.uint8)
    if code.size != length:
        raise ValueError(f"scrambler_gc returned {code.size} bits, expected {length}")
    return code


def descramble(values: np.ndarray, c_init: int) -> np.ndarray:
    """Hard bits or soft values 0..1: v -> 1 - v where the Gold code is 1."""
    code = gold_code(c_init, values.size)
    return np.where(code == 1, 1.0 - values, values)


# --------------------------------------------------------------------------- #
# Input / output
# --------------------------------------------------------------------------- #
def load_values(path: Path) -> tuple[np.ndarray, dict[str, Any]]:
    import h5py
    if not path.is_file():
        raise FileNotFoundError(f"Input file not found: {path} - run Get_Demapped_Bitstream.py first")
    with h5py.File(path, "r") as f:
        if INPUT_DATASET not in f:
            raise ValueError(f"{path.name} has no dataset '{INPUT_DATASET}'")
        values = np.asarray(f[INPUT_DATASET][()], dtype=np.float64).ravel()
        attrs = dict(f.attrs)
    if values.size == 0:
        raise ValueError(f"{path} contains an empty vector")
    if not np.isfinite(values).all() or values.min() < 0 or values.max() > 1:
        raise ValueError(f"{path} must hold bits 0/1 or soft values between 0 and 1")
    return values, attrs


def load_reference(path: Path) -> np.ndarray:
    import h5py
    if not path.is_file():
        raise FileNotFoundError(f"Compare file not found: {path}")
    with h5py.File(path, "r") as f:
        name = OUTPUT_DATASET if OUTPUT_DATASET in f else next(iter(f), None)
        if name is None:
            raise ValueError(f"{path} has no datasets")
        return np.asarray(f[name][()]).ravel().astype(np.uint8)


def save_blocks(path: Path, bits: np.ndarray, crc_pass: np.ndarray, attrs: dict[str, Any]) -> None:
    import h5py
    with h5py.File(path, "w") as f:
        f.create_dataset(OUTPUT_DATASET, data=bits)
        f.create_dataset("CRC_Pass", data=crc_pass)
        for k, v in attrs.items():
            f.attrs[k] = v


def get_int(params: dict[str, Any], section: str, key: str, minimum: int = 0) -> int:
    try:
        value = params[section][key]
    except (KeyError, TypeError):
        raise ValueError(f"{section}/{key} not set in {PARAMS_FILENAME} - run Initialize_Rx.py") from None
    if isinstance(value, bool) or not isinstance(value, int) or value < minimum:
        raise ValueError(f"{section}/{key} is {value!r} in {PARAMS_FILENAME}, expected an integer >= {minimum}")
    return value


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #
def decode(input_path: Path, params: dict[str, Any], iterations: int = DEFAULT_ITERATIONS
           ) -> tuple[np.ndarray, np.ndarray, dict[str, Any]]:
    """Return (transport-block bitstream, CRC pass per block, info)."""
    n_blocks = get_int(params, CALCULATED_SECTION, "AvailableDataBlocks", 1)
    word_size = get_int(params, CALCULATED_SECTION, "CodeWordSize", 1)
    zero_padding = get_int(params, CALCULATED_SECTION, "ZeroPadding", 0)
    tb_size = get_int(params, CALCULATED_SECTION, "TransportBlockSize", 1)
    seq_size = get_int(params, CALCULATED_SECTION, "ScrambledSequenceSize", 1)
    c_init = get_int(params, DEFINED_SECTION, "C_init_Dat", 0)
    if c_init > C_INIT_MAX:
        raise ValueError(f"{DEFINED_SECTION}/C_init_Dat is {c_init}, expected 0 to {C_INIT_MAX} "
                         "(it comes from the 8-bit control field C_init)")

    values, _ = load_values(input_path)
    log.info("Read %d values from %s", values.size, input_path)
    if values.size != seq_size:
        raise ValueError(f"{input_path.name} has {values.size} values but ScrambledSequenceSize = "
                         f"{seq_size} - run Initialize_Rx.py")
    if n_blocks * word_size + zero_padding != seq_size:
        raise ValueError(f"AvailableDataBlocks {n_blocks} x CodeWordSize {word_size} + ZeroPadding "
                         f"{zero_padding} != ScrambledSequenceSize {seq_size} - run Initialize_Rx.py")

    Sequence = descramble(values, c_init)
    log.info("Descrambled %d values with C_init_Dat = %d", Sequence.size, c_init)

    padding = Sequence[n_blocks * word_size:]
    padding_errors = int(np.count_nonzero(padding > 0.5))
    log.info("ZeroPadding: %d values, %d not decoded as 0", padding.size, padding_errors)

    decoder = Decoder(params, iterations)
    blocks, crc_pass, corrected_total = [], [], 0
    for i in range(n_blocks):
        tb, passed, corrected = decoder(Sequence[i * word_size:(i + 1) * word_size])
        if tb.size != tb_size:
            raise ValueError(f"Block {i}: decoded {tb.size} bits, TransportBlockSize is {tb_size}")
        blocks.append(tb)
        crc_pass.append(passed)
        corrected_total += corrected
        log.info("Block %d: CRC %s (%d bit(s) corrected by LDPC)", i, "PASS" if passed else "FAIL", corrected)

    bits = np.concatenate(blocks).astype(np.uint8)
    info = {"AvailableDataBlocks": n_blocks, "TransportBlockSize": tb_size,
            "CRC_Gen": decoder.crc_gen, "BlocksPassed": int(sum(crc_pass)),
            "CorrectedBits": corrected_total, "PaddingErrors": padding_errors,
            "C_init_Dat": c_init, "Iterations": iterations}
    return bits, np.asarray(crc_pass, dtype=np.uint8), info


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    ap = argparse.ArgumentParser(description="Decode the received encoded bitstream into transport blocks.")
    ap.add_argument("--input", type=Path,
                    help=f"encoded bitstream .h5; a relative name is looked up in the Rx directory "
                         f"(default: File_Rx/{INPUT_KEY})")
    ap.add_argument("--params", type=Path, help=f"path to {PARAMS_FILENAME} (default: Rx directory)")
    ap.add_argument("--out", type=Path,
                    help=f"output .h5; a relative name is put in the Rx directory (default: File_Rx/{OUTPUT_KEY})")
    ap.add_argument("--iterations", type=int, default=DEFAULT_ITERATIONS,
                    help=f"LDPC decoder iterations (default: {DEFAULT_ITERATIONS})")
    ap.add_argument("--compare", type=Path, nargs="?", const=DEFAULT_COMPARE,
                    help="compare with the Tx transport blocks "
                         f"(default file: {DEFAULT_COMPARE.relative_to(TX.parent)})")
    ap.add_argument("--ray", type=int, choices=range(1, MAX_RAYS + 1), metavar="N",
                    help="antenna (ray) 1-4: read and write its _RayN files. Default: the _Combined "
                         "files when the run has several antennas (Combine_Antennas_Rx.py), else _Ray1")
    ap.add_argument("-v", "--verbose", action="store_true", help="debug logging")
    return ap.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(argv)
    logging.basicConfig(
        level=logging.DEBUG if args.verbose else logging.INFO,
        format="%(asctime)s %(levelname)-7s %(message)s",
        datefmt="%H:%M:%S",
    )
    try:
        if importlib.util.find_spec("h5py") is None:
            raise ValueError("Reading/writing .h5 files needs h5py - install it with: pip install h5py")
        if args.iterations < 1:
            raise ValueError("--iterations must be at least 1")

        params = load_rx_module("FEC_LDPC_Rx").load_params(args.params or RX_DIR / PARAMS_FILENAME)
        files = params.get(FILE_SECTION, {})
        n_ant = antennas_in_run(params)
        in_name = args.input or Path(target_name(files.get(INPUT_KEY), args.ray, n_ant)
                                     if files.get(INPUT_KEY) else "")
        out_name = args.out or Path(target_name(files.get(OUTPUT_KEY), args.ray, n_ant)
                                    if files.get(OUTPUT_KEY) else "")
        log.info("Input: %s", target_label(args.ray, n_ant))
        if not str(in_name) or not str(out_name) or str(in_name) == "." or str(out_name) == ".":
            raise ValueError(f"{FILE_SECTION}/{INPUT_KEY} and {FILE_SECTION}/{OUTPUT_KEY} must be set "
                             f"in {PARAMS_FILENAME}")
        in_path = in_name if in_name.is_absolute() else RX_DIR / in_name
        out_path = out_name if out_name.is_absolute() else RX_DIR / out_name

        bits, crc_pass, info = decode(in_path, params, args.iterations)
        save_blocks(out_path, bits, crc_pass, {**info, "SourceFile": in_path.name,
                                                  "Ray": args.ray if args.ray is not None else (0 if n_ant > 1 else 1)})
        log.info("CRC passed for %d of %d block(s)", info["BlocksPassed"], info["AvailableDataBlocks"])
        log.info("Transport blocks saved to %s (%d bits)", out_path, bits.size)

        status = EXIT_OK if crc_pass.all() else EXIT_FAIL

        if args.compare:
            ref = load_reference(args.compare)
            if ref.size != bits.size:
                log.error("MISMATCH: Rx has %d bits, %s has %d", bits.size, args.compare.name, ref.size)
                return EXIT_FAIL
            errors = np.flatnonzero(ref != bits)
            if errors.size == 0:
                log.info("MATCH: Rx transport blocks equal %s (%d bits)", args.compare.name, bits.size)
            else:
                shown = ", ".join(map(str, errors[:SHOW_ERRORS])) + (", ..." if errors.size > SHOW_ERRORS else "")
                log.error("MISMATCH: %d of %d bits differ from %s (BER %.3e), first at bit(s) %s",
                          errors.size, bits.size, args.compare.name, errors.size / bits.size, shown)
                status = EXIT_FAIL
        return status

    except (FileNotFoundError, ValueError) as exc:
        log.error("%s", exc)
        return EXIT_ERROR
    except Exception:
        log.exception("Decoding failed")
        return EXIT_UNEXPECTED


if __name__ == "__main__":
    sys.exit(main())
