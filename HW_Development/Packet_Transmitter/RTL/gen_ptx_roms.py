#!/usr/bin/env python3
"""
gen_ptx_roms.py  (Flexlink_py/HW_Development/Packet_Transmitter/RTL)

Writes ptx_roms.v from ../PC/ptx_tables.npz (run ../PC/gen_ptx_tables.py first):

  ptx_tw_rom #(L)   IFFT twiddles W_L^j = exp(+j 2 pi j / L), j = 0 .. 3L/4 - 1, for L = 2048, 512,
                    128, 32, 8 (one per radix-2^2 stage pair); 18-bit signed Q16, registered output
  ptx_pre_rom       preamble: address 0 .. 63 Preamble A period, 64 .. 2111 Preamble B body;
                    16-bit signed I and Q, registered output
  ptx_type_rom      signal type of grid column k (0 .. 840) in a reference symbol, per
                    RefSignalSpacing code s (0: 3, 1: 6, 2: 12, 3: 24): 0 Data, 1 Ref_P0, 2 Ref_P1,
                    3 DC; address {s, k}
  ptx_ldpc_hdr      per code (address {CBS code, rate code}): base of its list in ptx_ldpc_nz,
                    number of nonzero circulants in the message columns, Z code, and the parity
                    column's shifts (rows 0 and x for the recursion, the p0 rotation)
  ptx_ldpc_nz       nonzero circulants of the message columns: {row, column, shift}
  ptx_il_rom        LDPC interleaver as {block, bit}: out[i] = cw[il[i]], il[i] = block * Z + bit;
                    address base(N) + i, bases 0, 648, 1944
  ptx_gold_start    x1, x2 of the LTE Gold code after the 1600-bit shift for any 31-bit c_init
                    (x2 is linear in c_init: XOR of 31 columns)
  ptx_gain_rom      payload output-stage gain for 13 dB backoff, address {Mod, RefSymbolSpacing code,
                    RefSignalSpacing code, PacketLength code}; also the preamble and control-field
                    gains (constants)
  ptx_bcc_il        control-field BCC interleaver (wiring)

    python gen_ptx_roms.py
"""
from __future__ import annotations

from pathlib import Path

import sys

import numpy as np

HERE = Path(__file__).resolve().parent
T = np.load(HERE.parent / "PC" / "ptx_tables.npz")
OUT = HERE / "ptx_roms.v"
SPACINGS = (3, 6, 12, 24)
N = 2048
sys.path.insert(0, str(HERE.parent / "PC"))
import ptx_reference as R  # noqa: E402


def s18(v: int) -> str:
    v = int(v)
    assert -(1 << 17) <= v < (1 << 17)
    return f"18'h{v & 0x3FFFF:05x}"


def s16(v: int) -> str:
    v = int(v)
    assert -(1 << 15) <= v < (1 << 15)
    return f"16'h{v & 0xFFFF:04x}"


def main() -> None:
    o = ["// ptx_roms.v - GENERATED by gen_ptx_roms.py from ../PC/ptx_tables.npz. Do not edit.",
         "`timescale 1ns / 1ps", ""]
    # twiddles
    o += ["module ptx_tw_rom #(parameter L = 2048) (",
          "  input  wire              clk,",
          "  input  wire              ce,",
          "  input  wire [10:0]       addr,",
          "  output wire signed [17:0] wr,",
          "  output wire signed [17:0] wi);",
          "  // L >= 512: block RAM (the register is the BRAM output register; without the attribute",
          "  // Vivado moves it into the DSP48 input register and builds the ROM from LUTs)",
          "  generate"]
    first = True
    for L in (2048, 512, 128, 32, 8):
        n = 3 * L // 4
        m = np.arange(n) * (N // L)
        o.append(f"  {'if' if first else 'else if'} (L == {L}) begin : g{L}")
        first = False
        attr = '(* rom_style = "block" *) ' if L >= 512 else ''
        o.append(f"    {attr}reg signed [17:0] r_wr, r_wi;")
        o.append("    assign wr = r_wr;")
        o.append("    assign wi = r_wi;")
        o.append("    always @(posedge clk) if (ce) case (addr)")
        for j in range(n):
            o.append(f"      11'd{j}: begin r_wr <= {s18(T['tw_re'][m[j]])}; r_wi <= {s18(T['tw_im'][m[j]])}; end")
        o.append("      default: begin r_wr <= 18'd0; r_wi <= 18'd0; end")
        o.append("    endcase")
        o.append("  end")
    o += ["  endgenerate", "endmodule", ""]
    # preamble
    o += ["module ptx_pre_rom (",
          "  input  wire              clk,",
          "  input  wire              ce,",
          "  input  wire [11:0]       addr,",
          "  output reg  signed [15:0] re,",
          "  output reg  signed [15:0] im);",
          "  always @(posedge clk) if (ce) case (addr)"]
    ar, ai, br, bi = T["pre_a_re"], T["pre_a_im"], T["pre_b_re"], T["pre_b_im"]
    for j in range(64):
        o.append(f"    12'd{j}: begin re <= {s16(ar[j])}; im <= {s16(ai[j])}; end")
    for j in range(N):
        o.append(f"    12'd{64 + j}: begin re <= {s16(br[j])}; im <= {s16(bi[j])}; end")
    o += ["    default: begin re <= 16'd0; im <= 16'd0; end", "  endcase", "endmodule", ""]
    # signal types of reference rows
    code = {40: 0, 10: 1, 20: 2, 30: 3}
    o += ["module ptx_type_rom (",
          "  input  wire        clk,",
          "  input  wire        ce,",
          "  input  wire [11:0] addr,      // {spacing code (2), k (10)}",
          "  output reg  [1:0]  t);        // 0 Data, 1 Ref_P0, 2 Ref_P1, 3 DC",
          "  always @(posedge clk) if (ce) case (addr)"]
    for si, S in enumerate(SPACINGS):
        row = T[f"ref_row_{S}"]
        for k in range(841):
            c = code[int(row[k])]
            if c:
                o.append(f"    12'd{(si << 10) | k}: t <= 2'd{c};")
    o += ["    default: t <= 2'd0;", "  endcase", "endmodule", ""]
    # LDPC encoder tables
    hdr, nz = [], []
    for cb, n in enumerate((648, 1296, 1944)):
        for rc, rate in enumerate(("12", "23", "34", "56")):
            c = R.code_of(f"{n}_{rate}")
            rows = sorted(r for r, _ in c.h)
            hs = dict(c.h)
            assert rows[0] == 0 and rows[2] == c.m - 1 and 0 < rows[1] < c.m - 1
            hroll = (c.Z - c.h_x) % c.Z
            ent = [(r, col, int(c.P[r, col])) for r in range(c.m) for col in range(c.kb) if c.P[r, col] >= 0]
            hdr.append((len(nz), len(ent), cb, hs[0], rows[1], hs[rows[1]], hroll))
            nz += ent
    o += ["module ptx_ldpc_hdr (",
          "  input  wire [3:0]  addr,      // {CBS code (2), rate code (2)}",
          "  output reg  [9:0]  base,",
          "  output reg  [7:0]  nnz,",
          "  output reg  [6:0]  h0s,       // shift of the p0 circulant in row 0",
          "  output reg  [3:0]  hxr,       // the other row (x) of the p0 column",
          "  output reg  [6:0]  hxs,",
          "  output reg  [6:0]  hroll);    // p0 = rot(sum of lambda, hroll)",
          "  always @* case (addr)"]
    for i, (base, cnt, cb, h0s, hxr, hxs, hroll) in enumerate(hdr):
        a = (i // 4) << 2 | (i % 4)
        o.append(f"    4'd{a}: begin base = 10'd{base}; nnz = 8'd{cnt}; h0s = 7'd{h0s}; hxr = 4'd{hxr}; "
                 f"hxs = 7'd{hxs}; hroll = 7'd{hroll}; end")
    o += ["    default: begin base = 10'd0; nnz = 8'd0; h0s = 7'd0; hxr = 4'd0; hxs = 7'd0; hroll = 7'd0; end",
          "  endcase", "endmodule", ""]
    o += ["module ptx_ldpc_nz (",
          "  input  wire        clk,",
          "  input  wire [9:0]  addr,",
          "  output reg  [15:0] e);        // {row (4), column (5), shift (7)}",
          "  always @(posedge clk) case (addr)"]
    for j, (r, col, sh) in enumerate(nz):
        o.append(f"    10'd{j}: e <= {{4'd{r}, 5'd{col}, 7'd{sh}}};")
    o += ["    default: e <= 16'd0;", "  endcase", "endmodule", ""]
    # interleaver as {block, bit}
    o += ["module ptx_il_rom (",
          "  input  wire        clk,",
          "  input  wire [11:0] addr,      // base(N) + i: 0 (648), 648 (1296), 1944 (1944)",
          "  output reg  [11:0] e);        // {block (5), bit (7)}",
          "  always @(posedge clk) case (addr)"]
    base = 0
    for n, z in ((648, 27), (1296, 54), (1944, 81)):
        il = T[f"il_{n}"]
        for i in range(n):
            v = int(il[i])
            o.append(f"    12'd{base + i}: e <= {{5'd{v // z}, 7'd{v % z}}};")
        base += n
    o += ["    default: e <= 12'd0;", "  endcase", "endmodule", ""]
    # Gold start
    x1s, _ = R.gold_start(0)
    cols = [R.gold_start(1 << i)[1] ^ R.gold_start(0)[1] for i in range(31)]
    rng = np.random.default_rng(5)
    for c in [0, 1, 128, 129, 130, 255, 0x7FFFFFFF, *rng.integers(0, 1 << 31, 20)]:
        x = 0
        for i in range(31):
            if (int(c) >> i) & 1:
                x ^= cols[i]
        assert x ^ R.gold_start(0)[1] == R.gold_start(int(c))[1]
    assert R.gold_start(0)[1] == 0
    o += ["module ptx_gold_start (",
          "  input  wire [30:0] c_init,",
          "  output wire [30:0] x1,",
          "  output wire [30:0] x2);",
          f"  assign x1 = 31'h{x1s:08x};"]
    for b in range(31):
        terms = [f"c_init[{i}]" for i in range(31) if (cols[i] >> b) & 1]
        o.append(f"  assign x2[{b}] = {' ^ '.join(terms) if terms else chr(49) + chr(39) + 'b0'};")
    o += ["endmodule", ""]
    # gains
    g0 = R.gains(R.TxConfig())
    o += ["module ptx_gain_rom (",
          "  input  wire [8:0]  addr,      // {Mod (2), RefSymbolSpacing code (2), RefSignalSpacing code (2), PacketLength code (3)}",
          "  output reg  [15:0] g_pl,",
          "  output wire [15:0] g_pre,",
          "  output wire [15:0] g_cf);",
          f"  assign g_pre = 16'd{g0['pre']};",
          f"  assign g_cf  = 16'd{g0['cf']};",
          "  always @* case (addr)"]
    for mi, mod in enumerate(("BPSK", "QPSK", "16QAM", "64QAM")):
        for ri, rs in enumerate((1, 3, 6, 12)):
            for si, S in enumerate(SPACINGS):
                for li, L in enumerate((37, 49, 73, 97, 121)):
                    g = R.gains(R.TxConfig(mod=mod, ref_sym=rs, ref_sig=S, plen=L, n=648, rate="12", rep=1))
                    assert g["pre"] == g0["pre"] and g["cf"] == g0["cf"]
                    o.append(f"    9'd{mi << 7 | ri << 5 | si << 3 | li}: g_pl = 16'd{g['pl']};")
    o += ["    default: g_pl = 16'd0;", "  endcase", "endmodule", ""]
    # BCC interleaver
    il = T["bcc_il"]
    o += ["module ptx_bcc_il (", "  input  wire [139:0] code,", "  output wire [139:0] il);"]
    o += [f"  assign il[{i}] = code[{int(il[i])}];" for i in range(140)]
    o += ["endmodule", ""]
    OUT.write_text("\n".join(o))
    print(f"Wrote {OUT} ({OUT.stat().st_size // 1024} KB)")


if __name__ == "__main__":
    main()
