#!/usr/bin/env python3
"""
gen_cf_roms.py  (Flexlink_py/HW_Development/Packet_Detector/RTL)

Writes cf_roms.v: the fixed tables of the control-field receiver, from PC/cf_reference.py
(which takes them from PC/cf_tables.py). Rerun only if those tables change:

    python gen_cf_roms.py

Modules (all with a registered output, one clock of latency):
  cf_twiddle_rom   512 x (18 + 18) bit: W^k = exp(-j 2 pi k / 1024), Q17 (TW_RE, TW_IM)
  cf_fir_map_rom   841 x (9 + 5) bit:   per tone k the first pilot of its 8-tap window
                                         (CF_FIR_START) and its coefficient set (0..24)
  cf_fir_coef_rom  25 x 8 x (16 + 16) bit: the coefficient sets, Q14 (CF_FIR_RE, CF_FIR_IM),
                                         address = set * 8 + tap
  cf_gold_rom      2200 x 1 bit:         descrambling sequence, gold(130) after 1600 steps
  cf_deint_rom     140 x 8 bit:          A index of code bit p (code[IDX[j]] = A[j], so
                                         entry p = j with IDX[j] = p)
  cf_ref_rom       280 x 1 bit:          1 = Ref_P0 pilot j is -1
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "PC"))
import cf_reference as CF  # noqa: E402

N_TONES = 841


def hexv(v, bits):
    return f"{bits}'h{int(v) & ((1 << bits) - 1):0{(bits + 3) // 4}x}"


def rom(name, comment, abits, dbits, entries, default=0):
    rows = "\n".join(f"            {abits}'d{a}: d = {hexv(v, dbits)};" for a, v in entries)
    return f"""// {comment}
module {name} (
    input  wire              clk,
    input  wire [{abits - 1}:0]  addr,
    output reg  [{dbits - 1}:0] q
);
    reg [{dbits - 1}:0] d;
    always @* begin
        case (addr)
{rows}
            default: d = {hexv(default, dbits)};
        endcase
    end
    always @(posedge clk) q <= d;
endmodule
"""


def main():
    # twiddles
    tw = [(k, ((int(CF.TW_RE[k]) & 0x3FFFF) << 18) | (int(CF.TW_IM[k]) & 0x3FFFF)) for k in range(512)]
    assert max(abs(CF.TW_RE).max(), abs(CF.TW_IM).max()) < (1 << 17)

    # FIR: distinct coefficient sets in order of first use
    sets, set_of = [], []
    for k in range(N_TONES):
        key = (tuple(CF.CF_FIR_RE[k]), tuple(CF.CF_FIR_IM[k]))
        if key not in sets:
            sets.append(key)
        set_of.append(sets.index(key))
    assert len(sets) <= 32 and max(CF.CF_FIR_START) + 7 < 280
    fmap = [(k, (int(CF.CF_FIR_START[k]) << 5) | set_of[k]) for k in range(N_TONES)]
    coef = []
    for si, (re, im) in enumerate(sets):
        for i in range(8):
            assert abs(re[i]) < (1 << 15) and abs(im[i]) < (1 << 15)
            coef.append((si * 8 + i, ((re[i] & 0xFFFF) << 16) | (im[i] & 0xFFFF)))

    gold = [(i, int(b)) for i, b in enumerate(CF.CF_GOLD)]
    inv = np.zeros(140, np.int64)
    inv[CF.CF_IDX] = np.arange(140)
    deint = [(p, int(inv[p])) for p in range(140)]
    ref = [(j, 1 if CF.CF_REF[j] < 0 else 0) for j in range(280)]
    assert np.array_equal(CF.CF_P0_K, np.arange(280) * 3 + 2)

    src = ["// cf_roms.v  (Flexlink_py/HW_Development/Packet_Detector/RTL)",
           "//",
           "// GENERATED by gen_cf_roms.py from PC/cf_reference.py - do not edit.",
           "`timescale 1ns / 1ps", "`default_nettype none", "",
           rom("cf_twiddle_rom", "W^k, k = 0..511: {re[17:0], im[17:0]}, Q17", 9, 36, tw),
           rom("cf_fir_map_rom", "tone k: {first pilot [13:5], coefficient set [4:0]}", 10, 14, fmap),
           rom("cf_fir_coef_rom", f"{len(sets)} sets x 8 taps: {{re[31:16], im[15:0]}}, Q14", 8, 32, coef),
           rom("cf_gold_rom", "descrambling bit of data tone i (1 = negate)", 12, 1, gold),
           rom("cf_deint_rom", "accumulator index of code bit p", 8, 8, deint),
           rom("cf_ref_rom", "1 = Ref_P0 pilot j is -1", 9, 1, ref),
           "`default_nettype wire", ""]
    out = HERE / "cf_roms.v"
    out.write_text("\n".join(src))
    print(f"Wrote {out}: {len(sets)} FIR coefficient sets")


if __name__ == "__main__":
    main()
