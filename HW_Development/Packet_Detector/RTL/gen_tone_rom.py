#!/usr/bin/env python3
"""
gen_tone_rom.py  (Flexlink_py/HW_Development/Packet_Detector/RTL)

Writes pd_tone_rom.v: the tone check's cosine table, TONE_COS from pd_reference.py
(1024 x 16 bit, amplitude 32767), as a dual-port ROM with registered outputs. The sine is the
same table a quarter turn earlier (TONE_SIN[a] == TONE_COS[a - 256], checked here), so one ROM
with two read ports gives both. Rerun only if the table in pd_reference.py changes:

    python gen_tone_rom.py
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "PC"))
import pd_reference as ref  # noqa: E402

n = 1 << ref.TONE_LUT_BITS
assert all(ref.TONE_SIN[a] == ref.TONE_COS[(a - n // 4) % n] for a in range(n))
rows = "\n".join(f"            10'd{a}: c = 16'h{ref.TONE_COS[a] & 0xFFFF:04x};" for a in range(n))
src = f"""// pd_tone_rom.v  (Flexlink_py/HW_Development/Packet_Detector/RTL)
//
// GENERATED by gen_tone_rom.py from pd_reference.TONE_COS - do not edit.
// Cosine table, 1024 x 16 bit signed (amplitude 32767), two read ports, one clock of latency.
// sin(a) = cos(a - 256). Vivado maps it to one block RAM.
`timescale 1ns / 1ps
`default_nettype none

module pd_tone_rom (
    input  wire               clk,
    input  wire [9:0]         addr_a,
    input  wire [9:0]         addr_b,
    output wire signed [15:0] dout_a,
    output wire signed [15:0] dout_b
);
    (* rom_style = "block" *) reg [15:0] qa;
    (* rom_style = "block" *) reg [15:0] qb;
    assign dout_a = qa;
    assign dout_b = qb;
    function [15:0] cos_t;
        input [9:0] a;
        reg   [15:0] c;
        begin
            case (a)
{rows}
            default: c = 16'h0000;
            endcase
            cos_t = c;
        end
    endfunction

    always @(posedge clk) begin
        qa <= cos_t(addr_a);
        qb <= cos_t(addr_b);
    end
endmodule

`default_nettype wire
"""
(HERE / "pd_tone_rom.v").write_text(src)
print(f"wrote {HERE / 'pd_tone_rom.v'}")
