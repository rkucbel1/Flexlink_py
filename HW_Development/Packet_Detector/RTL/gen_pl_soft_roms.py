#!/usr/bin/env python3
"""
gen_pl_soft_roms.py  (Flexlink_py/HW_Development/Packet_Detector/RTL)

Writes pl_soft_roms.v, the fixed tables of the payload demapper and combiner (pl_demap.v,
pl_comb.v), from PC/pl_tables.npz (pl_reference.py). Rerun only if those tables change:

    python gen_pl_soft_roms.py

  pl_dmask_rom   8192 x 1 bit, LUT ROM, asynchronous: address {row, column}, row = S code
                 (0..3: a reference row of RefSignalSpacing 3 / 6 / 12 / 24) or 4 (a data row);
                 1 = the tone is a Data RE (pl_reference.signal_types == DATA)
  pl_ilinv_rom   4096 x 11 bit, block RAM, two read ports, registered: the inverse LDPC
                 interleaver, i = ilinv[v] with il[i] = v (code[v] = Lq[i]); N = 648 at 0,
                 1296 at 648, 1944 at 1944
  pl_gold_init   combinational: the Gold code's two shift registers after the 1600-step start
                 (cf_reference.gold): x1 is a constant, x2 a linear (XOR) function of C_init
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
T = np.load(HERE.parent / "PC" / "pl_tables.npz")
DATA = 40
ILBASE = {648: 0, 1296: 648, 1944: 1944}


def main() -> int:
    mask = np.zeros(8192, np.int64)
    for si, S in enumerate((3, 6, 12, 24)):
        mask[si * 1024: si * 1024 + 841] = T[f"ref_row_{S}"] == DATA
    mask[4 * 1024: 4 * 1024 + 841] = T["data_row"] == DATA
    ilinv = np.zeros(4096, np.int64)
    for n, b in ILBASE.items():
        il = T[f"il_{n}"]
        assert sorted(il.tolist()) == list(range(n))
        inv = np.empty(n, np.int64)
        inv[il] = np.arange(n)
        ilinv[b:b + n] = inv

    def step(r1, r2):
        r1 = (r1 >> 1) | (((r1 ^ (r1 >> 3)) & 1) << 30)
        r2 = (r2 >> 1) | (((r2 ^ (r2 >> 1) ^ (r2 >> 2) ^ (r2 >> 3)) & 1) << 30)
        return r1, r2
    x1 = 1
    for _ in range(1600):
        x1, _ = step(x1, 0)
    cols = []
    for b in range(8):
        r2 = 1 << b
        for _ in range(1600):
            _, r2 = step(0, r2)
        cols.append(r2)
    eqs, ZERO = [], "1'b0"
    for o in range(31):
        terms = [f"ci[{b}]" for b in range(8) if (cols[b] >> o) & 1]
        eqs.append(f"    assign x2[{o}] = {' ^ '.join(terms) or ZERO};")
    gold = "\n".join(eqs)
    ones = "\n".join(f"        mem[{a}] = 1'b1;" for a in np.flatnonzero(mask))
    ilrows = "\n".join(f"        mem[{a}] = 11'd{int(v)};" for a, v in enumerate(ilinv) if v)
    v = f"""// pl_soft_roms.v  (Flexlink_py/HW_Development/Packet_Detector/RTL)
// GENERATED by gen_pl_soft_roms.py - do not edit. Tables of the payload demapper and combiner.
`timescale 1ns / 1ps
`default_nettype none

module pl_dmask_rom (
    input  wire [12:0] addr,
    output wire        d
);
    (* rom_style = "distributed" *) reg mem [0:8191];
    integer i;
    initial begin
        for (i = 0; i < 8192; i = i + 1) mem[i] = 1'b0;
{ones}
    end
    assign d = mem[addr];
endmodule

module pl_ilinv_rom (
    input  wire        clk,
    input  wire [11:0] addr_a,
    input  wire [11:0] addr_b,
    output reg  [10:0] da,
    output reg  [10:0] db
);
    (* rom_style = "block" *) reg [10:0] mem [0:4095];
    integer i;
    initial begin
        for (i = 0; i < 4096; i = i + 1) mem[i] = 11'd0;
{ilrows}
    end
    always @(posedge clk) begin
        da <= mem[addr_a];
        db <= mem[addr_b];
    end
endmodule

module pl_gold_init (
    input  wire [7:0]  ci,                     // C_init (x2 = C_init before the start)
    output wire [30:0] x1,
    output wire [30:0] x2
);
    assign x1 = 31'h{x1:08x};
{gold}
endmodule

`default_nettype wire
"""
    (HERE / "pl_soft_roms.v").write_text(v)
    print(f"Wrote pl_soft_roms.v ({int(mask.sum())} data-tone entries, {len(ILBASE)} interleavers)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
