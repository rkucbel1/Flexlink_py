#!/usr/bin/env python3
"""
gen_pl_ldpc_rom.py  (Flexlink_py/HW_Development/Packet_Detector/RTL)

Writes pl_ldpc_rom.v, the code tables of the LDPC decoder core (pl_ldpc_core.v), from the
802.11n prototype matrices in PC/pl_tables.npz. Rerun only if those tables change:

    python gen_pl_ldpc_rom.py

Code index = 4 * n_sel + rate_sel   (n_sel 0 / 1 / 2 = N 648 / 1296 / 1944, Z = 27 G with
G = 1 / 2 / 3; rate_sel 0 / 1 / 2 / 3 = 1/2, 2/3, 3/4, 5/6, the order of FEC_A_Flag).

Modules:
  pl_ldpc_edge_rom   2048 x 18 bit, two read ports, registered outputs (one clock; block RAM):
                     the circulants ("edges") of
                     every layer of every code, layer after layer. Entry =
                     {last, eo[4:0], sh27[1:0], s27[4:0], col[4:0]}
                       col   block column 0..23
                       s27,  the circulant shift sh = 27 sh27 + s27 (0 .. Z-1)
                       sh27
                       eo    the edge's position in the layer's natural column order (the model's
                             min-sum tie-break: the first minimum in column order)
                       last  last edge of its layer
                     Within a layer the edges are reordered for speed (columns the previous layer
                     does not write first, then the others in the order the previous layer writes
                     them). The order cannot change the result: every column appears once per
                     layer and the tie-break uses eo.
  pl_ldpc_code_rom   12 entries, combinational: {base[10:0], n_ent[6:0], kb[4:0], nl[3:0], g[1:0]}
                       base   first entry of the code in pl_ldpc_edge_rom
                       n_ent  entries (circulants) of the code
                       kb     message block columns (K = 27 G kb)
                       nl     layers (prototype rows)
                       g      G - 1
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
T = np.load(HERE.parent / "PC" / "pl_tables.npz")
CODES = [f"{n}_{r}" for n in (648, 1296, 1944) for r in ("12", "23", "34", "56")]


def layers(t):
    P = T[f"P_{t}"]
    return [[(int(c), int(P[r, c])) for c in np.flatnonzero(P[r] >= 0)] for r in range(P.shape[0])]


def ordered(L):
    """Per layer: list of (col, shift, eo) in processing order."""
    nl = len(L)
    cols = [[c for c, _ in l] for l in L]
    orders = [list(c) for c in cols]
    for _ in range(6):
        for k in range(nl):
            prev = set(orders[k - 1])
            nxt = set(cols[(k + 1) % nl])
            free = sorted((c for c in cols[k] if c not in prev), key=lambda c: (c not in nxt, c))
            dep = [c for c in orders[k - 1] if c in cols[k]]
            orders[k] = free + dep
    out = []
    for k in range(nl):
        sh = dict(L[k])
        eo = {c: i for i, c in enumerate(cols[k])}
        out.append([(c, sh[c], eo[c]) for c in orders[k]])
    return out


def main() -> int:
    entries, hdr = [], []
    for t in CODES:
        L = layers(t)
        Z = int(T[f"Z_{t}"])
        G = Z // 27
        kb = 24 - len(L)
        base = len(entries)
        for lay in ordered(L):
            assert len(lay) <= 31
            for i, (c, sh, eo) in enumerate(lay):
                last = int(i == len(lay) - 1)
                entries.append((last << 17) | (eo << 12) | ((sh // 27) << 10) | ((sh % 27) << 5) | c)
        hdr.append((base, len(entries) - base, kb, len(L), G - 1))
    assert len(entries) <= 2048
    rows = "\n".join(f"        mem[{a}] = 18'h{v:05x};" for a, v in enumerate(entries))
    hrows = "\n".join(f"            4'd{i}: d = {{11'd{b}, 7'd{n}, 5'd{kb}, 4'd{nl}, 2'd{g}}};"
                      for i, (b, n, kb, nl, g) in enumerate(hdr))
    v = f"""// pl_ldpc_rom.v  (Flexlink_py/HW_Development/Packet_Detector/RTL)
// GENERATED by gen_pl_ldpc_rom.py - do not edit. LDPC decoder code tables (see the script).
`timescale 1ns / 1ps
`default_nettype none

module pl_ldpc_edge_rom (
    input  wire        clk,
    input  wire [10:0] addr_a,
    output reg  [17:0] d_a,
    input  wire [10:0] addr_b,
    output reg  [17:0] d_b
);
    (* rom_style = "block" *) reg [17:0] mem [0:2047];
    integer i;
    initial begin
        for (i = 0; i < 2048; i = i + 1) mem[i] = 18'h00000;
{rows}
    end
    always @(posedge clk) d_a <= mem[addr_a];
    always @(posedge clk) d_b <= mem[addr_b];
endmodule

module pl_ldpc_code_rom (
    input  wire [3:0]  code,
    output reg  [28:0] d
);
    always @* begin
        case (code)
{hrows}
            default: d = 29'd0;
        endcase
    end
endmodule

`default_nettype wire
"""
    (HERE / "pl_ldpc_rom.v").write_text(v)
    print(f"Wrote pl_ldpc_rom.v: {len(entries)} edges, max layer degree "
          f"{max(len(l) for t in CODES for l in layers(t))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
