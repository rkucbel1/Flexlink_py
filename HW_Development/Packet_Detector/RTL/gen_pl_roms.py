#!/usr/bin/env python3
"""
gen_pl_roms.py  (Flexlink_py/HW_Development/Packet_Detector/RTL)

Writes pl_roms.v, the fixed tables of the payload channel estimate (pl_chest.v), from
PC/pl_tables.npz (pl_reference.py). Rerun only if those tables change:

    python gen_pl_roms.py

S code = RefSignalSpacing code (0 / 1 / 2 / 3 = 3 / 6 / 12 / 24). All ROMs have a registered
output (one clock), block RAM.

  pl_coef_rom   8192 x 64 bit: FIR coefficients, two taps per word {wi1, wr1, wi0, wr0} (16 bit
                each, / 2^14). Word = table base + set * 4 + tap pair. The tables follow each other
                in the order (S, class, mode) = (3,0,0), (3,0,1), (3,1,0) ... (24,0,1);
                pl_coef_base(S code, class, mode) gives the base (combinational function).
  pl_tone_rom   4096 x 18 bit, address {S code, column}: {noise, set[7:0], start[8:0]}
                start  first pilot of the tone's 8-tap window, set  its coefficient set (the same
                grouping for every class and mode of an S), noise  the column is a noise tone of a
                reference row (Ref_P1 or in-band DC, step 7)
  pl_pil_rom    2048 x 16 bit, address {S code, pilot index}: {bit, win[14:0]}  pilot bit (Ref_P0,
                0 / 1) and the Hann window for the delay profile (step 3)
"""
import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
T = np.load(HERE.parent / "PC" / "pl_tables.npz")
SP = (3, 6, 12, 24)


def main() -> int:
    coef = []
    base = {}
    tone = np.zeros(4096, np.int64)
    for si, S in enumerate(SP):
        nc = int(T[f"n_classes_{S}"])
        groups = None
        sets_of = {}
        for c in range(nc):
            for v in (0, 1):
                wr, wi = T[f"fir_re_{S}_{c}_{v}"], T[f"fir_im_{S}_{c}_{v}"]
                keys = [(tuple(a), tuple(b)) for a, b in zip(wr, wi)]
                uniq = {}
                idx = [uniq.setdefault(k, len(uniq)) for k in keys]
                if groups is None:
                    groups = idx
                assert idx == groups, "tone grouping differs between tables"
                base[(si, c, v)] = len(coef)
                for (ar, ai) in sorted(uniq, key=lambda k: uniq[k]):
                    for p in range(4):
                        w = 0
                        for h in range(2):
                            r, i = int(ar[2 * p + h]), int(ai[2 * p + h])
                            assert -32768 <= r < 32768 and -32768 <= i < 32768
                            w |= ((r & 0xFFFF) | ((i & 0xFFFF) << 16)) << (32 * h)
                        coef.append(w)
        st = T[f"fir_start_{S}_0"]
        t0 = T[f"ref_row_{S}"]
        noise = (t0 == 20) | ((t0 == 30) & (np.arange(841) >= 1) & (np.arange(841) <= 839))
        for k in range(841):
            assert groups[k] < 256 and st[k] < 512
            tone[si * 1024 + k] = (int(noise[k]) << 17) | (groups[k] << 9) | int(st[k])
    assert len(coef) <= 8192
    pil = np.zeros(2048, np.int64)
    for si, S in enumerate(SP):
        b, w = T[f"pilot_bits_{S}"], T[f"win_{S}"]
        for i in range(b.size):
            pil[si * 512 + i] = (int(b[i]) << 15) | int(w[i])

    def mem(name, width, depth, vals):
        rows = "\n".join(f"        mem[{a}] = {width}'h{int(v):0{(width + 3) // 4}x};"
                         for a, v in enumerate(vals) if v)
        return rows

    cases = "\n".join(f"            {{2'd{si}, 2'd{c}, 1'b{v}}}: pl_coef_base = 13'd{b};"
                      for (si, c, v), b in sorted(base.items()))
    v = f"""// pl_roms.v  (Flexlink_py/HW_Development/Packet_Detector/RTL)
// GENERATED by gen_pl_roms.py - do not edit. Tables of the payload channel estimate.
`timescale 1ns / 1ps
`default_nettype none

module pl_coef_rom (
    input  wire        clk,
    input  wire [12:0] addr,
    output reg  [63:0] d
);
    (* rom_style = "block" *) reg [63:0] mem [0:8191];
    integer i;
    initial begin
        for (i = 0; i < 8192; i = i + 1) mem[i] = 64'd0;
{mem("c", 64, 8192, coef)}
    end
    always @(posedge clk) d <= mem[addr];
endmodule

module pl_tone_rom (
    input  wire        clk,
    input  wire [11:0] addr,
    output reg  [17:0] d
);
    (* rom_style = "block" *) reg [17:0] mem [0:4095];
    integer i;
    initial begin
        for (i = 0; i < 4096; i = i + 1) mem[i] = 18'd0;
{mem("t", 18, 4096, tone)}
    end
    always @(posedge clk) d <= mem[addr];
endmodule

module pl_pil_rom (
    input  wire        clk,
    input  wire [10:0] addr,
    output reg  [15:0] d
);
    (* rom_style = "block" *) reg [15:0] mem [0:2047];
    integer i;
    initial begin
        for (i = 0; i < 2048; i = i + 1) mem[i] = 16'd0;
{mem("p", 16, 2048, pil)}
    end
    always @(posedge clk) d <= mem[addr];
endmodule

`default_nettype wire
"""
    (HERE / "pl_roms.v").write_text(v)
    inc = f"""// pl_coef_base.vh  GENERATED by gen_pl_roms.py - do not edit.
// First word in pl_coef_rom of the table (S code, class, mode).
function [12:0] pl_coef_base;
    input [1:0] s;
    input [1:0] c;
    input       m;
    begin
        case ({{s, c, m}})
{cases}
            default: pl_coef_base = 13'd0;
        endcase
    end
endfunction
"""
    (HERE / "pl_coef_base.vh").write_text(inc)
    print(f"Wrote pl_roms.v ({len(coef)} coefficient words) and pl_coef_base.vh")
    return 0


if __name__ == "__main__":
    sys.exit(main())
