#!/usr/bin/env python3
"""
gen_cf_tables.py  (Flexlink_py/HW_Development/Packet_Detector/PC)

Writes cf_tables.py: the fixed tables of the control-field receiver (cf_reference.py), so the
bit-true model never depends on floating-point library details at run time:

  CF_REF_NEG       the 280 Ref_P0 pilot values of the control field (bit j = 1: pilot j is -1),
                   from ReferenceSignals/Ref_P0_3_1.h5 (checked when h5py and the file are there)
  CF_IDX           the BCC interleaver table for 140 bits (Interleave_BCC.py, 0-based)
  CF_FIR_START     per tone k (0..840): first of the 8 pilots its channel estimate uses
  CF_FIR_RE / _IM  per tone: 8 coefficients, signed, / 2^CF_FIR_FRAC
                   LMMSE weights for a flat delay profile over CF_FIR_DELAYS samples and pilot
                   noise CF_FIR_NOISE, restricted to the 8 nearest pilots (spec section 4.4)

    python gen_cf_tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent

CF_FIR_TAPS = 8
CF_FIR_FRAC = 14
CF_FIR_DELAYS = (-8, 24)          # samples, [start, end)
CF_FIR_NOISE = 0.5

REF_NEG_HEX = "3e436aa545a1eb0c339103a6af00d03c60801108e634bf5c82249a8aef21ac0465e465"
IDX_140 = [62, 88, 45, 106, 127, 37, 121, 85, 83, 54, 113, 99, 1, 12, 19, 23, 111, 79, 96, 59,
           97, 94, 55, 7, 31, 112, 89, 5, 34, 47, 137, 8, 44, 64, 72, 110, 117, 14, 136, 124,
           40, 66, 76, 77, 78, 81, 93, 61, 118, 115, 65, 11, 125, 73, 38, 25, 134, 50, 123, 20,
           15, 53, 109, 138, 75, 6, 41, 105, 52, 92, 128, 9, 10, 27, 82, 60, 84, 32, 74, 48,
           91, 43, 56, 135, 67, 28, 100, 57, 29, 17, 133, 98, 102, 33, 46, 116, 3, 103, 49, 2,
           68, 35, 130, 140, 107, 18, 126, 30, 39, 24, 132, 22, 42, 95, 70, 131, 101, 4, 104, 120,
           129, 13, 69, 63, 21, 36, 122, 114, 90, 108, 16, 58, 139, 26, 119, 87, 86, 71, 51, 80]


def pilot_tones() -> np.ndarray:
    """Tones (-420..420) of the 280 P0 pilots of a control-field reference symbol."""
    return np.arange(2, 840, 3) - 420


def fir_table(taps=CF_FIR_TAPS, frac=CF_FIR_FRAC, delays=CF_FIR_DELAYS, noise=CF_FIR_NOISE):
    pt = pilot_tones().astype(float)
    d = np.arange(*delays)

    def corr(dk):
        return np.exp(-2j * np.pi * np.multiply.outer(dk, d) / 1024).mean(axis=-1)
    start, cre, cim = [], [], []
    for t in np.arange(-420, 421).astype(float):
        near = np.sort(np.argsort(np.abs(pt - t), kind="stable")[:taps])
        assert np.all(np.diff(near) == 1)
        p = pt[near]
        w = corr(np.subtract.outer(np.array([t]), p)) @ np.linalg.inv(corr(np.subtract.outer(p, p)) + noise * np.eye(taps))
        q = np.round(w[0] * (1 << frac))
        start.append(int(near[0]))
        cre.append([int(v) for v in q.real])
        cim.append([int(v) for v in q.imag])
    return start, cre, cim


def check_ref() -> None:
    root = next((p for p in [HERE, *HERE.parents] if (p / "flexlink_paths.py").is_file()), None)
    f = root / "ReferenceSignals" / "Ref_P0_3_1.h5" if root else None
    try:
        import h5py
    except ImportError:
        print("Note: no h5py - pilot table not checked against Ref_P0_3_1.h5")
        return
    if f is None or not f.is_file():
        print("Note: Ref_P0_3_1.h5 not found - pilot table not checked")
        return
    with h5py.File(f, "r") as h:
        x = np.asarray(h["data"][()]).ravel()
    re = x["r"] if x.dtype.names else x.real
    v = int(REF_NEG_HEX, 16)
    ok = all(((v >> j) & 1) == (1 if re[j] < 0 else 0) for j in range(280)) and len(re) == 280
    print(f"Pilot table {'matches' if ok else 'DOES NOT MATCH'} {f}")
    if not ok:
        sys.exit(1)


def main() -> int:
    check_ref()
    start, cre, cim = fir_table()
    out = HERE / "cf_tables.py"
    lines = ['"""GENERATED by gen_cf_tables.py - do not edit. Tables of the control-field receiver."""',
             f"CF_FIR_TAPS = {CF_FIR_TAPS}",
             f"CF_FIR_FRAC = {CF_FIR_FRAC}",
             f"CF_FIR_DELAYS = {CF_FIR_DELAYS}",
             f"CF_FIR_NOISE = {CF_FIR_NOISE}",
             f'CF_REF_NEG = int("{REF_NEG_HEX}", 16)',
             f"CF_IDX = {[i - 1 for i in IDX_140]}",
             f"CF_FIR_START = {start}",
             "CF_FIR_RE = ["] + [f"    {r}," for r in cre] + ["]", "CF_FIR_IM = ["] + \
            [f"    {r}," for r in cim] + ["]"]
    out.write_text("\n".join(lines) + "\n")
    print(f"Wrote {out}: {len(start)} tones x {CF_FIR_TAPS} taps, "
          f"{len({(tuple(a), tuple(b)) for a, b in zip(cre, cim)})} distinct coefficient sets")
    return 0


if __name__ == "__main__":
    sys.exit(main())
