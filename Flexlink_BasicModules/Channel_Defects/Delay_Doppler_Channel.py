"""
Delay_Doppler_Channel.py

NumPy replacement for the MATLAB function Delay_Doppler_Channel, which used
comm.RicianChannel. No MATLAB toolboxes or special libraries are needed:
only NumPy.

Model (tapped delay line, same structure as comm.RicianChannel):
  * Path gains: Power (dB) converted to linear and normalized so the
    average total channel power is 1 (MATLAB NormalizePathGains = true).
  * Fading: each path is a Rayleigh process with a Jakes (classic U-shaped)
    Doppler spectrum, generated by sum-of-sinusoids (Zheng & Xiao model).
    Every call draws a new, independent channel realization, as the MATLAB
    code did by releasing the channel object after each call.
  * Rician first path: when KFactor > 0, the first path gets a line-of-sight
    component with power K/(K+1) of that path's power, rotating at
    DirectPathDopplerShift (Hz). KFactor = 0 gives pure Rayleigh fading.
  * Fractional delays: each path delay is applied with a windowed-sinc
    interpolation filter, so delays need not be multiples of the sample
    period. The filter is made causal, which delays the whole output by
    `filter_delay` samples (MATLAB's ChannelFilterDelay plays the same
    role). The output has the same length as the input.
"""

import json

import numpy as np


def delay_doppler_channel(sample_rate, k_factor, doppler_freq, delays, power_db,
                          signal, direct_path_doppler=-20.0,
                          num_sinusoids=16, sinc_half_length=8,
                          rng=None, return_info=False):
    """
    Parameters
    ----------
    sample_rate : float
        Sample rate in Hz.
    k_factor : float
        Rician K-factor of the first path, linear (not dB). 0 = Rayleigh.
    doppler_freq : float
        Maximum Doppler shift in Hz.
    delays : array_like
        Path delays in seconds.
    power_db : array_like
        Average path powers in dB (same length as delays).
    signal : array_like, complex, shape (N,)
        Input samples.
    direct_path_doppler : float
        Doppler shift of the line-of-sight component in Hz (MATLAB code
        used -20 Hz).
    num_sinusoids : int
        Sinusoids per quadrature component in the fading generator.
    sinc_half_length : int
        Extra sinc taps on each side of the delay span for fractional
        delays. Larger = more accurate, longer filter delay.
    rng : numpy.random.Generator or int, optional
        Random generator or seed for a reproducible channel.
    return_info : bool
        If True, also return a dict with the filter delay, the sinc filter
        and the fading coefficients.

    Returns
    -------
    output : ndarray of complex128, shape (N,)
    info : dict (only if return_info is True)
    """
    rng = np.random.default_rng(rng)
    x = np.asarray(signal, dtype=complex).ravel()
    n = len(x)
    delays = np.asarray(delays, dtype=float).ravel()
    power_db = np.asarray(power_db, dtype=float).ravel()
    if delays.shape != power_db.shape:
        raise ValueError("delays and power_db must have the same length")
    n_paths = len(delays)

    # Average path powers, normalized to total power 1
    path_power = 10 ** (power_db / 10)
    path_power /= path_power.sum()

    # Fading coefficients h[path, sample]
    t = np.arange(n) / sample_rate
    fading = np.empty((n_paths, n), dtype=complex)
    for p in range(n_paths):
        fading[p] = _jakes_fading(t, doppler_freq, num_sinusoids, rng)

    # Rician line-of-sight component on the first path
    if k_factor > 0:
        los = np.exp(2j * np.pi * direct_path_doppler * t)
        fading[0] = (np.sqrt(k_factor / (k_factor + 1)) * los
                     + np.sqrt(1 / (k_factor + 1)) * fading[0])

    fading *= np.sqrt(path_power)[:, None]

    # Windowed-sinc fractional-delay filters g[path, tap]
    delay_samples = delays * sample_rate
    first_tap = int(np.floor(delay_samples.min())) - sinc_half_length
    last_tap = int(np.ceil(delay_samples.max())) + sinc_half_length
    taps = np.arange(first_tap, last_tap + 1)
    filter_delay = -first_tap                       # makes the filter causal
    sinc_filters = np.empty((n_paths, len(taps)))
    for p in range(n_paths):
        offset = taps - delay_samples[p]
        w = np.where(np.abs(offset) <= sinc_half_length + 1,
                     0.5 + 0.5 * np.cos(np.pi * offset / (sinc_half_length + 1)),
                     0.0)
        g = np.sinc(offset) * w
        sinc_filters[p] = g / g.sum()               # unity DC gain

    # Time-varying filtering: y[n] = sum_p h_p[n] * (g_p * x)[n]
    output = np.zeros(n, dtype=complex)
    for p in range(n_paths):
        delayed = np.convolve(x, sinc_filters[p])[:n]
        output += fading[p] * delayed

    if return_info:
        return output, {"filter_delay": filter_delay,
                        "filter_taps": taps + filter_delay,
                        "sinc_filters": sinc_filters,
                        "fading": fading}
    return output


def _jakes_fading(t, fd, m, rng):
    """
    Unit-power complex Rayleigh process with a Jakes Doppler spectrum
    (Zheng & Xiao sum-of-sinusoids model with random phases).
    """
    theta = rng.uniform(-np.pi, np.pi)
    alpha = (2 * np.pi * np.arange(1, m + 1) - np.pi + theta) / (4 * m)
    phi_c = rng.uniform(-np.pi, np.pi, m)
    phi_s = rng.uniform(-np.pi, np.pi, m)
    w = 2 * np.pi * fd * t[:, None]
    xc = np.sqrt(2 / m) * np.cos(w * np.cos(alpha) + phi_c).sum(axis=1)
    xs = np.sqrt(2 / m) * np.cos(w * np.sin(alpha) + phi_s).sum(axis=1)
    return (xc + 1j * xs) / np.sqrt(2)


if __name__ == "__main__":
    with open("Channel_Defects.json", "r") as f:
        cfg = json.load(f)
    s = cfg["Settings"]
    model = s["MultipathModel"].upper()
    if model == "FIR":
        raise SystemExit("MultipathModel is FIR; use Get_Multipath_Filter.py")
    prof = s["MultipathProfiles"][model]

    rng = np.random.default_rng(0)
    x = (rng.standard_normal(100000)
         + 1j * rng.standard_normal(100000)) / np.sqrt(2)
    y, info = delay_doppler_channel(s["SampleRate"], s["KFactor"],
                                    s["DopplerFreq"], prof["Delays"],
                                    prof["Power"], x, rng=rng,
                                    return_info=True)
    print(f"{model}: {len(prof['Delays'])} paths, "
          f"filter delay {info['filter_delay']} samples, "
          f"{info['sinc_filters'].shape[1]} filter taps")
    print(f"Output/input power: {np.mean(abs(y)**2) / np.mean(abs(x)**2):.3f}"
          " (one realization; averages to 1)")
