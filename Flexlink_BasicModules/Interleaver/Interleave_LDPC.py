"""
Interleave_LDPC.py

Python port of the MATLAB Interleave() function (interleave direction only)
for the LDPC code path.

The interleaving index vector is read from one of:
    Interleaver_648.h5, Interleaver_1296.h5, Interleaver_1944.h5
(generated by Generate_Interleaver_Vector.py).
"""

import os
import numpy as np
import h5py

# Folder containing the .h5 files (defaults to the folder of this script)
INTERLEAVER_DIR = os.path.dirname(os.path.abspath(__file__))

_FILES = {
    648: "Interleaver_648.h5",
    1296: "Interleaver_1296.h5",
    1944: "Interleaver_1944.h5",
}

# Dataset name written by Generate_Interleaver_Vector.py
_DATASET_NAME = "InterleaverIndex"

# Cache so each file is only read from disk once
_cache = {}


def _load_index_vector(CBS):
    """Load the interleaving index vector for the given code block size.

    Returns a 0-based, 1-D int array of length CBS.
    """
    if CBS in _cache:
        return _cache[CBS]

    if CBS not in _FILES:
        raise ValueError(f"CBS must be one of {sorted(_FILES)}, got {CBS}")

    path = os.path.join(INTERLEAVER_DIR, _FILES[CBS])
    with h5py.File(path, "r") as f:
        idx = f[_DATASET_NAME][()].astype(np.int64).ravel()
        index_base = int(f.attrs.get("index_base", 0))

    if idx.size != CBS:
        raise ValueError(f"Index vector in {path} has length {idx.size}, expected {CBS}")

    # Files may be stored 1-based (MATLAB style, --one-based); convert to 0-based
    if index_base == 1:
        idx = idx - 1

    if idx.min() != 0 or idx.max() != CBS - 1 or np.unique(idx).size != CBS:
        raise ValueError(f"Index vector in {path} is not a valid permutation of 0..{CBS-1}")

    _cache[CBS] = idx
    return idx


def Interleave_LDPC(MatrixToInterleave, CBS):
    """Interleave code block(s) using the LDPC interleaver.

    Equivalent to the MATLAB loop:
        output(1, i) = input(1, InterleavingIndexVector(1, i))

    Parameters
    ----------
    MatrixToInterleave : array-like
        Shape (CBS,) for a single code block, or (N, CBS) to interleave
        N code blocks at once (each row is interleaved independently).
    CBS : int
        Code block size: 648, 1296, or 1944. Selects which .h5 file is used.

    Returns
    -------
    InvCodeBlkMatrix : np.ndarray
        Interleaved data, same shape as MatrixToInterleave.
    """
    x = np.asarray(MatrixToInterleave)

    if x.shape[-1] != CBS:
        raise ValueError(f"Last dimension of input is {x.shape[-1]}, expected CBS={CBS}")

    idx = _load_index_vector(CBS)

    # output[..., i] = input[..., idx[i]]
    InvCodeBlkMatrix = x[..., idx]
    return InvCodeBlkMatrix


if __name__ == "__main__":
    # Quick self-test: interleaving a ramp should return the index vector itself
    for cbs in (648, 1296, 1944):
        try:
            ramp = np.arange(cbs)
            out = Interleave_LDPC(ramp, cbs)
            print(f"CBS={cbs}: OK, first 8 outputs = {out[:8]}")
        except FileNotFoundError as e:
            print(f"CBS={cbs}: {e}")
